test('ICS contains stable IDs, UTC times, five events a day and safe UTF-8 folding', () => {
  const c = defaultConfig(); c.locations[0].name = 'مدينة'.repeat(40) + ',;\nEND:VEVENT';
  const text = calendarIcs(c, '2026-09-13', '2026-09-14', new Date('2026-01-01T00:00:00Z'));
  assert.equal((text.match(/BEGIN:VEVENT/g) ?? []).length, 10);
  assert.equal((text.match(/DTSTART:\d{8}T\d{6}Z/g) ?? []).length, 10);
  assert.ok(text.split('\r\n').every(line => Buffer.byteLength(line) <= 75));
  assert.ok(!text.includes('\r\nEND:VEVENT\r\nEND:VEVENT'));
  assert.equal(text, calendarIcs(c, '2026-09-13', '2026-09-14', new Date('2026-01-01T00:00:00Z')));
});
