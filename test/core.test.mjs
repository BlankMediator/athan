test('Hanafi changes Asr without moving the other prayers', () => {
  const c = defaultConfig(), a = calculateDay(c, '2026-09-13');
  c.calculation.madhab = 'Hanafi'; const b = calculateDay(c, '2026-09-13');
  assert.ok(+b.times.asr - +a.times.asr > 30 * 60000);
  for (const p of TIMES.filter(p => p !== 'asr')) assert.equal(+a.times[p], +b.times[p]);
});
test('all minute adjustments apply once, with no accumulated mutation', () => {
  const c = defaultConfig(), before = calculateDay(c, '2026-09-13');
  c.calculation.adjustments.fajr = -3; c.calculation.adjustments.maghrib = 5;
  const after = calculateDay(c, '2026-09-13');
  assert.equal(+after.times.fajr - +before.times.fajr, -180000);
  assert.equal(+after.times.maghrib - +before.times.maghrib, 300000);
  assert.deepEqual(calculateDay(c, '2026-09-13'), after);
});
test('Melbourne DST spring transition changes local display without a UTC hour jump', () => {
  const c = defaultConfig(), a = calculateDay(c, '2026-10-03'), b = calculateDay(c, '2026-10-04');
  const minute = d => { const [h, m] = formatTime(d, a.timeZone, false).split(':').map(Number); return h * 60 + m; };
  assert.ok(minute(b.times.dhuhr) - minute(a.times.dhuhr) >= 58);
  assert.ok(Math.abs((+b.times.dhuhr - +a.times.dhuhr) / 60000 - 1440) <= 2);
});
test('Melbourne autumn DST transition shifts local display back', () => {
  const c = defaultConfig(), a = calculateDay(c, '2026-04-04'), b = calculateDay(c, '2026-04-05');
  const minute = d => { const [h, m] = formatTime(d, a.timeZone, false).split(':').map(Number); return h * 60 + m; };
  assert.ok(minute(b.times.dhuhr) - minute(a.times.dhuhr) <= -58);
});
