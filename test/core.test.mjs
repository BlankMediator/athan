test('audio sequences are serialized and a new prayer interrupts an active reminder', async () => {
  const calls = []; let started;
  const beginning = new Promise(r => started = r);
  const player = (file, options) => {
    calls.push(file);
    if (file === 'reminder') return new Promise((resolve, reject) => { options.signal.addEventListener('abort', () => reject(new Error('interrupted'))); started(); });
    return Promise.resolve('ok');
  };
  const queue = new AudioQueue(player), settings = { volume: 0, maxSeconds: 1 };
  const reminder = queue.enqueue(['reminder'], 1, 'reminder', settings);
  const rejected = assert.rejects(reminder, /interrupted/);
  await beginning; await queue.enqueue(['athan', 'dua'], 1, 'athan', settings); await rejected;
  assert.deepEqual(calls, ['reminder', 'athan', 'dua']); await queue.stop();
});
test('expired queued audio does not play', async () => {
  let called = false; const queue = new AudioQueue(async () => { called = true; return ''; }, () => 1000);
  await assert.rejects(queue.enqueue(['file'], 1, 'athan', { volume: 0, maxSeconds: 1 }, 999), /expired/);
  assert.equal(called, false); await queue.stop();
});
test('a new Athan moves ahead of reminders already waiting in the audio queue', async () => {
  const calls = []; let started;
  const beginning = new Promise(r => started = r);
  const player = (file, options) => {
    calls.push(file);
    if (file === 'active') return new Promise((resolve, reject) => { options.signal.addEventListener('abort', () => reject(new Error('interrupted'))); started(); });
    return Promise.resolve('ok');
  };
  const queue = new AudioQueue(player), settings = { volume: 0, maxSeconds: 1 };
  const active = assert.rejects(queue.enqueue(['active'], 1, 'reminder', settings), /interrupted/);
  await beginning;
  const waiting = queue.enqueue(['waiting-reminder'], 1, 'reminder', settings);
  const prayer = queue.enqueue(['athan', 'dua'], 1, 'athan', settings);
  await Promise.all([active, waiting, prayer]);
  assert.deepEqual(calls, ['active', 'athan', 'dua', 'waiting-reminder']); await queue.stop();
});
